/* InternTrack — tracker layer, export page.
   Moved out of the inline <script> in export.html, with the status filter
   from the master design added to the query string.

   The file itself is generated by the server (export_csv / export_pdf); this
   only picks the name, offers a Save As dialog where the browser supports
   one, and reports what happened. */
(function () {
  'use strict';

  var page = IT.$('export-page');
  if (!page) return;

  var URLS = { csv: page.dataset.csvUrl, pdf: page.dataset.pdfUrl };
  var DEFAULTS = { csv: 'internship_applications', pdf: 'internship_report' };
  var PICKER_TYPES = {
    csv: { description: 'CSV file', accept: { 'text/csv': ['.csv'] } },
    pdf: { description: 'PDF file', accept: { 'application/pdf': ['.pdf'] } }
  };

  var status = IT.$('export-status');
  var note = IT.$('export-status-note');

  function say(msg) { if (note) note.textContent = msg; }

  function buildURL(kind, filename) {
    var params = new URLSearchParams({ filename: filename });
    if (status && status.value) params.set('status', status.value);
    return URLS[kind] + '?' + params.toString();
  }

  async function download(kind) {
    var input = IT.$(kind + '-filename');
    var filename = (input && input.value.trim()) || DEFAULTS[kind];

    say('Preparing your file…');

    try {
      var response = await fetch(buildURL(kind, filename));
      if (!response.ok) throw new Error('The server could not generate the file.');
      var blob = await response.blob();

      if (window.showSaveFilePicker) {
        var handle = await window.showSaveFilePicker({
          suggestedName: filename + '.' + kind,
          types: [PICKER_TYPES[kind]]
        });
        var writable = await handle.createWritable();
        await writable.write(blob);
        await writable.close();
        say('Saved.');
        IT.toast(kind.toUpperCase() + ' saved.');
      } else {
        var link = document.createElement('a');
        link.href = URL.createObjectURL(blob);
        link.download = filename + '.' + kind;
        document.body.appendChild(link);
        link.click();
        link.remove();
        URL.revokeObjectURL(link.href);
        say('Downloaded to your usual downloads folder — this browser cannot ask where to save.');
        IT.toast(kind.toUpperCase() + ' downloaded.');
      }
    } catch (err) {
      say(err.name === 'AbortError' ? 'Save cancelled.' : 'Something went wrong: ' + err.message);
    }
  }

  document.addEventListener('click', function (e) {
    var btn = e.target.closest('[data-export]');
    if (!btn) return;
    e.preventDefault();
    download(btn.dataset.export);
  });
})();
